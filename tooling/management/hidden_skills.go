package management

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"tricell-hive/integrations/codex"
	"tricell-hive/integrations/target"
)

// A hidden skill is one whose SKILL.md frontmatter sets
// disable-model-invocation: true. Codex reads a skill's invocation policy from
// agents/openai.yaml, so for each such skill the manager generates that file
// and records it like any managed skill file, with a source of its own that is
// not a file of content/. The source names the skill, which makes it generated
// in the sense of generatedSource: a release never carries it, so a hand-written
// copy is rejected whether it comes from a stored release or a source checkout.
// SKILL.md and every host's catalogue link stay as they are for any skill.
var (
	skillEntrySource  = regexp.MustCompile(`^content/skills/([a-z0-9]+(-[a-z0-9]+)*)/SKILL\.md$`)
	skillPolicySource = regexp.MustCompile(`^content/skills/([a-z0-9]+(-[a-z0-9]+)*)/` + regexp.QuoteMeta(codex.SkillPolicyFile) + `$`)
)

// skillPolicySourceOf returns the generated source of a skill's policy file.
func skillPolicySourceOf(entrySource string) (string, bool) {
	m := skillEntrySource.FindStringSubmatch(entrySource)
	if m == nil {
		return "", false
	}
	return "content/skills/" + m[1] + "/" + codex.SkillPolicyFile, true
}

// generatedSkillPolicy reports whether source names a generated policy file.
func generatedSkillPolicy(source string) bool { return skillPolicySource.MatchString(source) }

// validRecordedSkillPolicy checks a recorded policy file's shape: a skill
// file in the folder of the skill its source names, owned by Codex alone.
func validRecordedSkillPolicy(r Record) error {
	m := skillPolicySource.FindStringSubmatch(r.Target.Source)
	path := r.Target.Path
	if m == nil || r.Target.Kind != "skill" || path != codex.SkillPolicyPath(filepath.Dir(filepath.Dir(path))) || filepath.Base(filepath.Dir(filepath.Dir(path))) != m[1] {
		return fmt.Errorf("invalid recorded skill policy")
	}
	for _, c := range r.Consumers {
		if c.Host != "codex" {
			return fmt.Errorf("invalid skill policy consumer")
		}
	}
	return nil
}

// skillPolicyTargets returns the policy files wanted next to the Codex skill
// entries in bindings. With a release (install) a file is wanted for each
// hidden skill of that release; without one (any other action) it is wanted
// where state already records it, so removal and status see what was written.
func skillPolicyTargets(bindings []target.Target, state State, release *Release) ([]target.Target, error) {
	var out []target.Target
	for _, t := range bindings {
		if t.Host != "codex" || t.Kind != "skill" {
			continue
		}
		source, ok := skillPolicySourceOf(t.Source)
		if !ok {
			continue
		}
		p := t
		p.Source, p.Path = source, codex.SkillPolicyPath(filepath.Dir(t.Path))
		if release != nil {
			if !codex.HiddenFromModel(payload(release, t.Source)) {
				continue
			}
		} else if r, recorded := state.Records[p.Path]; !recorded || r.Target.Source != source {
			continue
		}
		if err := target.Safe(p.Path); err != nil {
			return nil, err
		}
		out = append(out, p)
	}
	return out, nil
}

// renderSkillPolicy returns the policy file for a resolved target, after
// checking that the release still hides the skill it belongs to.
func renderSkillPolicy(t target.Target, p Plan) ([]byte, error) {
	m := skillPolicySource.FindStringSubmatch(t.Source)
	if m == nil || p.Release == nil {
		return nil, fmt.Errorf("invalid skill policy resource")
	}
	if !codex.HiddenFromModel(payload(p.Release, "content/skills/"+m[1]+"/SKILL.md")) {
		return nil, fmt.Errorf("skill %s is not hidden in this release; regenerate plan", m[1])
	}
	return codex.RenderSkillPolicy(), nil
}

// rejectHandWrittenPolicies fails when a skill folder of a source checkout
// holds a policy file: the manager generates it, so a written one would be
// silently dropped from the release or could contradict the frontmatter.
func rejectHandWrittenPolicies(skillEntries []string) error {
	for _, entry := range skillEntries {
		policy := codex.SkillPolicyPath(filepath.Dir(entry))
		if _, err := os.Lstat(policy); err == nil {
			return fmt.Errorf("invalid source %s: %s is generated by the manager from disable-model-invocation, remove the file", policy, codex.SkillPolicyFile)
		} else if !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}
