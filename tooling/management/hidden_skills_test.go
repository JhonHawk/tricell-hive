func TestRecordedPolicyShapeIsValidated(t *testing.T) {
	o := hiddenOptions(t)
	apply(t, plan(t, "install", o))
	s := stateFor(t, o)
	r := s.Records[policyPath(o)]
	bad := r
	bad.Consumers = []Consumer{{"claude", "user", o.Home}}
	s.Records[policyPath(o)] = bad
	if err := normalizeState(&s); err == nil {
		t.Fatal("policy owned by a host other than Codex accepted")
	}
	s = stateFor(t, o)
	bad = r
	bad.Target.Source = "content/skills/other/agents/openai.yaml"
	s.Records[policyPath(o)] = bad
	if err := normalizeState(&s); err == nil {
		t.Fatal("policy recorded for another skill accepted")
	}
	s = stateFor(t, o)
	bad = r
	bad.Target.Kind = "hook"
	s.Records[policyPath(o)] = bad
	if err := normalizeState(&s); err == nil {
		t.Fatal("policy recorded as another kind accepted")
	}
}
