// A stage packet is one Markdown file per key of a flow's assets/stage.json:
// the text of the rule leaves the manifest lists, in order, so a flow reads
// them in one call. Like a hidden skill's policy file (hidden_skills.go) it is
// generated, so a release never carries it and a hand-written copy is rejected
// from a stored release and from a source checkout. It lives in the flow's
// installed folder, for every host that installs the flow, and is recorded as
// a managed skill file with a source of its own.
const (
	stagePacketMaxBytes = 24000
	stagePacketMaxLines = 1000
)

var (
	// handWrittenPacket is any top-level skill file a reader could take for a
	// packet; only the manager writes those, from assets/stage.json.
	handWrittenPacket = regexp.MustCompile(`^stage.*\.md$`)
	stagePacketFile   = regexp.MustCompile(`^stage(-[a-z]+)?\.md$`)
	stageManifestKey  = regexp.MustCompile(`^stage(-[a-z]+)?$`)
	stagePacketSource = regexp.MustCompile(`^content/skills/([a-z0-9]+(-[a-z0-9]+)*)/(stage(?:-[a-z]+)?)\.md$`)
	stageManifestPath = regexp.MustCompile(`^content/skills/([a-z0-9]+(-[a-z0-9]+)*)/assets/stage\.json$`)
)

// generatedStagePacket reports whether source names a generated packet.
func generatedStagePacket(source string) bool { return stagePacketSource.MatchString(source) }

func stagePacketSourceOf(flow, key string) string {
	return "content/skills/" + flow + "/" + key + ".md"
}

// validRecordedStagePacket checks a recorded packet's shape: a skill file named
// after its key, in the folder of the flow its source names.
func validRecordedStagePacket(r Record) error {
	m := stagePacketSource.FindStringSubmatch(r.Target.Source)
	p := r.Target.Path
	if m == nil || r.Target.Kind != "skill" || filepath.Base(p) != m[3]+".md" || filepath.Base(filepath.Dir(p)) != m[1] {
		return fmt.Errorf("invalid recorded stage packet")
	}
	return nil
}

// rejectHandWrittenPackets fails when a skill folder of a source checkout holds
// a file named like a packet: the manager generates it from assets/stage.json.
func rejectHandWrittenPackets(skillEntries []string) error {
	for _, entry := range skillEntries {
		names, err := os.ReadDir(filepath.Dir(entry))
		if err != nil {
			return err
		}
		for _, n := range names {
			if handWrittenPacket.MatchString(n.Name()) {
				return fmt.Errorf("invalid source %s: stage packets are generated by the manager from assets/stage.json, remove the file", filepath.Join(filepath.Dir(entry), n.Name()))
			}
		}
	}
	return nil
}

// stageManifest is a parsed assets/stage.json: its keys in file order and the
// members of each, as written (paths relative to content/skills/).
type stageManifest struct {
	Keys    []string
	Members map[string][]string
}

// parseStageManifest reads a manifest strictly: one JSON object whose keys are
// distinct, match stageManifestKey and hold a non-empty array of distinct,
// clean relative .md paths.
func parseStageManifest(data []byte) (stageManifest, error) {
	m := stageManifest{Members: map[string][]string{}}
	dec := json.NewDecoder(bytes.NewReader(data))
	if tok, err := dec.Token(); err != nil || tok != json.Delim('{') {
		return m, fmt.Errorf("want a JSON object")
	}
	for dec.More() {
		tok, err := dec.Token()
		key, ok := tok.(string)
		if err != nil || !ok {
			return m, fmt.Errorf("want a JSON object")
		}
		if !stageManifestKey.MatchString(key) {
			return m, fmt.Errorf("unknown key %q: want stage or stage-<letters>", key)
		}
		if _, dup := m.Members[key]; dup {
			return m, fmt.Errorf("key %q appears twice", key)
		}
		var members []string
		if err := dec.Decode(&members); err != nil {
			return m, fmt.Errorf("key %q: want an array of paths", key)
		}
		if len(members) == 0 {
			return m, fmt.Errorf("key %q lists no members", key)
		}
		seen := map[string]bool{}
		for _, member := range members {
			if !strings.HasSuffix(member, ".md") || path.Clean(member) != member || strings.HasPrefix(member, "/") || strings.HasPrefix(member, "../") || strings.Contains(member, "\\") {
				return m, fmt.Errorf("key %q: member %q is not a clean relative .md path", key, member)
			}
			if seen[member] {
				return m, fmt.Errorf("key %q: member %q appears twice", key, member)
			}
			seen[member] = true
		}
		m.Keys = append(m.Keys, key)
		m.Members[key] = members
	}
	if tok, err := dec.Token(); err != nil || tok != json.Delim('}') {
		return m, fmt.Errorf("want a JSON object")
	}
	if _, err := dec.Token(); err != io.EOF {
		return m, fmt.Errorf("text after the object")
	}
	if len(m.Keys) == 0 {
		return m, fmt.Errorf("no keys")
	}
	return m, nil
}

// stageManifests returns the manifest of each flow of a release, by flow name.
func stageManifests(r *Release) (map[string]stageManifest, error) {
	out := map[string]stageManifest{}
	for _, f := range r.Files {
		m := stageManifestPath.FindStringSubmatch(f.Path)
		if m == nil {
			continue
		}
		parsed, err := parseStageManifest(f.Data)
		if err != nil {
			return nil, fmt.Errorf("invalid stage manifest %s: %w", f.Path, err)
		}
		out[m[1]] = parsed
	}
	return out, nil
}

var frontmatter = regexp.MustCompile(`(?s)\A---\r?\n.*?\r?\n---[ \t]*(?:\r?\n|\z)`)

func packetAnchor(member string) string {
	for a := range headingAnchors("## " + member) {
		return a
	}
	return ""
}

// renderStagePackets renders every packet of a release, by source path. It
// fails on a bad manifest, a missing member or a packet over its limits, and
// names the manifest and the key.
func renderStagePackets(r *Release) (map[string][]byte, error) {
	manifests, err := stageManifests(r)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	for _, f := range r.Files {
		files[f.Path] = f.Data
	}
	out := map[string][]byte{}
	for flow, manifest := range manifests {
		manifestPath := "content/skills/" + flow + "/assets/stage.json"
		for _, key := range manifest.Keys {
			fail := func(format string, args ...any) error {
				return fmt.Errorf("invalid stage manifest %s: packet %q: %s", manifestPath, key, fmt.Sprintf(format, args...))
			}
			members := map[string]string{}
			for _, member := range manifest.Members[key] {
				source := "content/skills/" + member
				if _, ok := files[source]; !ok {
					return nil, fail("member %s is not in this release", member)
				}
				members[source] = strings.TrimSuffix(member, ".md")
			}
			flowDir := "content/skills/" + flow
			var b strings.Builder
			var names []string
			for _, member := range manifest.Members[key] {
				source := "content/skills/" + member
				name := members[source]
				text := frontmatter.ReplaceAllString(string(files[source]), "")
				text = strings.Trim(text, "\r\n")
				if b.Len() > 0 {
					b.WriteString("\n\n")
				}
				b.WriteString("## " + name + "\n\n")
				b.WriteString(rewritePacketLinks(text, source, flowDir, members))
				names = append(names, name)
			}
			fmt.Fprintf(&b, "\n\n<!-- hive packet end: %s · %s -->\n", key, strings.Join(names, ","))
			packet := b.String()
			if len(packet) > stagePacketMaxBytes {
				return nil, fail("%d bytes, over the limit of %d bytes", len(packet), stagePacketMaxBytes)
			}
			if lines := strings.Count(packet, "\n"); lines > stagePacketMaxLines {
				return nil, fail("%d lines, over the limit of %d lines", lines, stagePacketMaxLines)
			}
			out[stagePacketSourceOf(flow, key)] = []byte(packet)
		}
	}
	return out, nil
}

// renderStagePacket returns the packet a resolved target names.
func renderStagePacket(t target.Target, p Plan) ([]byte, error) {
	if p.Release == nil || !generatedStagePacket(t.Source) {
		return nil, fmt.Errorf("invalid stage packet resource")
	}
	packets, err := renderStagePackets(p.Release)
	if err != nil {
		return nil, err
	}
	body, ok := packets[t.Source]
	if !ok {
		return nil, fmt.Errorf("stage packet %s is not in this release; regenerate plan", t.Source)
	}
	return body, nil
}

// stagePacketPayloads returns the packets of a release as release files, so the
// links of each are validated against the files and anchors of the release.
func stagePacketPayloads(r Release) ([]Payload, error) {
	packets, err := renderStagePackets(&r)
	if err != nil {
		return nil, err
	}
	var out []Payload
	for source, data := range packets {
		out = append(out, Payload{Path: source, Data: data, Mode: 0o644})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

// rewritePacketLinks rewrites the relative links of a member, outside fenced
// code, for the packet it joins: inline links and reference-style definitions
// alike. A link without an anchor to a member of the same packet points to that
// member's heading in the packet; a link with an anchor, to a member or within
// one, to the member's file with its anchor; any other relative link resolves
// from the flow's folder. Absolute, remote and skill: destinations stay.
func rewritePacketLinks(text, memberSource, flowDir string, members map[string]string) string {
	rel := func(target string) string {
		r, err := filepath.Rel(flowDir, target)
		if err != nil {
			return target
		}
		return filepath.ToSlash(r)
	}
	rewrite := func(raw string) string {
		u, err := url.Parse(raw)
		if raw == "" || err != nil || u.Scheme != "" || u.Host != "" {
			return raw
		}
		p, fragment := raw, ""
		if i := strings.Index(raw, "#"); i >= 0 {
			p, fragment = raw[:i], raw[i:]
		}
		if p == "" {
			if fragment == "#" {
				return raw
			}
			return rel(memberSource) + fragment
		}
		if strings.HasPrefix(p, "/") || strings.HasPrefix(p, "~") {
			return raw
		}
		resolved := path.Join(path.Dir(memberSource), p)
		if name, ok := members[resolved]; ok && fragment == "" {
			return "#" + packetAnchor(name)
		}
		out := rel(resolved)
		if strings.HasSuffix(p, "/") && !strings.HasSuffix(out, "/") {
			out += "/"
		}
		return out + fragment
	}
	return mdlinks.MapOutsideFences(text, func(line string) string {
		line = rewriteDestinations(line, inlineResourceLink, rewrite)
		return rewriteDestinations(line, definedResourceLink, rewrite)
	})
}

// rewriteDestinations replaces the destination (the first group) of every match
// of re in line with fn of it, keeping angle brackets around it.
func rewriteDestinations(line string, re *regexp.Regexp, fn func(string) string) string {
	matches := re.FindAllStringSubmatchIndex(line, -1)
	if matches == nil {
		return line
	}
	var b strings.Builder
	last := 0
	for _, m := range matches {
		start, end := m[2], m[3]
		b.WriteString(line[last:start])
		raw := line[start:end]
		out := fn(strings.Trim(raw, "<>"))
		if strings.HasPrefix(raw, "<") {
			out = "<" + out + ">"
		}
		b.WriteString(out)
		last = end
	}
	b.WriteString(line[last:])
	return b.String()
}

// stagePacketTargets returns the packets wanted next to the skill entries in
// bindings, for each host that installs the skill. With a release (install) one
// is wanted per key of the skill's manifest; without one (any other action) it
// is wanted where state already records it, so removal and status see what was
// written.
func stagePacketTargets(bindings []target.Target, state State, release *Release) ([]target.Target, error) {
	var manifests map[string]stageManifest
	if release != nil {
		var err error
		if manifests, err = stageManifests(release); err != nil {
			return nil, err
		}
	}
	var out []target.Target
	for _, t := range bindings {
		if t.Kind != "skill" {
			continue
		}
		m := skillEntrySource.FindStringSubmatch(t.Source)
		if m == nil {
			continue
		}
		flow := m[1]
		var keys []string
		if release != nil {
			keys = manifests[flow].Keys
		} else {
			for _, r := range state.Records {
				if sm := stagePacketSource.FindStringSubmatch(r.Target.Source); sm != nil && sm[1] == flow && filepath.Dir(r.Target.Path) == filepath.Dir(t.Path) {
					keys = append(keys, sm[3])
				}
			}
			sort.Strings(keys)
		}
		for _, key := range keys {
			p := t
			p.Source, p.Path = stagePacketSourceOf(flow, key), filepath.Join(filepath.Dir(t.Path), key+".md")
			if err := target.Safe(p.Path); err != nil {
				return nil, err
			}
			out = append(out, p)
		}
	}
	return out, nil
}
