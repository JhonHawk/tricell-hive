package codex

import (
	"path/filepath"
	"regexp"
	"strings"
)

// SkillPolicyFile is the path, inside a skill folder, of the file Codex reads
// for a skill's invocation policy.
const SkillPolicyFile = "agents/openai.yaml"

// SkillPolicyPath returns where the policy of the skill in skillDir lives.
func SkillPolicyPath(skillDir string) string {
	return filepath.Join(skillDir, filepath.FromSlash(SkillPolicyFile))
}

// RenderSkillPolicy returns the policy file of a skill the model must not load
// on its own: Codex lists the skill only when a person or an index names it.
func RenderSkillPolicy() []byte {
	return []byte("# Generated by Hive. Do not edit: the manager removes it when the skill is no longer hidden.\npolicy:\n  allow_implicit_invocation: false\n")
}

var hiddenFlag = regexp.MustCompile(`^disable-model-invocation:[ \t]*(true|"true"|'true')[ \t]*(#.*)?$`)

// HiddenFromModel reports whether the frontmatter of a SKILL.md sets
// disable-model-invocation to true. Only the frontmatter counts: the same
// line in the body is text.
func HiddenFromModel(skill []byte) bool {
	lines := strings.Split(strings.ReplaceAll(string(skill), "\r\n", "\n"), "\n")
	if len(lines) == 0 || strings.TrimRight(lines[0], " \t") != "---" {
		return false
	}
	for _, line := range lines[1:] {
		if strings.TrimRight(line, " \t") == "---" {
			return false
		}
		if hiddenFlag.MatchString(line) {
			return true
		}
	}
	return false
}
